"""Regression test for apply_state.rollback losing the triggering user (#48).

apply_state.rollback used to audit-record with hardcoded
``username="system", ip="127.0.0.1"`` regardless of whether the
rollback was manual (admin via /apply/rollback) or automatic
(watchdog expiry). The router also recorded its own audit row,
producing duplicate entries and losing the real user.

Fix: ``rollback()`` accepts ``username``/``ip`` keyword args; the
router passes the requesting admin and stops recording a duplicate.
"""

from __future__ import annotations

from typing import Any

from app.tasks import apply_state


def _admin(tokens: dict[str, str]) -> dict[str, str]:
    return {"Authorization": f"Bearer {tokens['admin']}"}


def test_manual_rollback_records_real_user(client: object, tokens: dict[str, str]) -> None:
    h = _admin(tokens)
    # Arm a plan first by setting a static network config.
    iface = "eth0"
    resp = client.post(  # type: ignore[attr-defined]
        f"/api/settings/network/{iface}",
        json={
            "method": "static",
            "address": "10.0.0.42",
            "netmask": "255.255.255.0",
            "gateway": "10.0.0.1",
            "dns": "1.1.1.1",
            "rollback_armed_s": 60,
            "confirm": True,
        },
        headers=h,
    )
    assert resp.status_code == 200, resp.text
    plan_id = resp.json()["plan_id"]

    # Trigger the manual rollback.
    rollback_resp = client.post(  # type: ignore[attr-defined]
        f"/api/settings/network/{iface}/apply/rollback",
        json={"plan_id": plan_id, "confirm": True},
        headers=h,
    )
    assert rollback_resp.status_code == 200, rollback_resp.text

    # Audit log must have exactly one apply_rollback row, attributed
    # to the requesting admin (NOT "system") (#48).
    audit = client.get(  # type: ignore[attr-defined]
        "/api/security/audit?action=apply_rollback&limit=20", headers=h
    ).json()
    rows = [r for r in audit["entries"] if r.get("target") == f"network:{iface}" and r.get("new_value") == "manual"]
    assert len(rows) == 1, f"expected exactly one manual rollback audit row, got {rows}"
    assert (
        rows[0]["username"] == "admin"
    ), f"manual rollback must record the triggering admin, got {rows[0]['username']!r}"

    # And the legacy set_network_rollback row must be gone (it was the
    # duplicate the router used to record in addition to apply_state's
    # own audit entry).
    legacy = client.get(  # type: ignore[attr-defined]
        "/api/security/audit?action=set_network_rollback&limit=20", headers=h
    ).json()
    assert legacy["entries"] == [], f"legacy set_network_rollback audit row should be gone, got {legacy['entries']}"


# --- #149: per-kind attribution tests --------------------------------------
"""Each rollback kind must propagate username/ip to the audit row.
Don't #48 says the audit row reflects the *triggering user*, not the
hardcoded system/127.0.0.1 defaults. These tests pin that contract
for each registered rollback kind by stubbing the handler and
capturing the audit call.

The handler itself does not audit — it only reverts state. The audit
row is generated by ``rollback()`` (single plan) or
``rollback_bundle()`` (bundle) which both take ``username``/``ip``
kwargs. The test pins that any direct caller (router, watchdog, or
test) cannot lose attribution by forgetting to pass them.
"""


class _StubDB:
    """Capture the audit and apply_plans writes without a live DB."""

    def __init__(self) -> None:
        self.executes: list[tuple[str, tuple[Any, ...]]] = []
        self._next_id = 0
        self._rows: dict[int, dict[str, Any]] = {}

    def arm_plan(self, plan_id: int = 1) -> None:
        """Pre-populate the stub with an armed plan so rollback() can find it."""
        self._rows[plan_id] = {"id": plan_id, "status": "armed"}

    async def execute(self, sql: str, params: tuple[Any, ...] = ()) -> int:
        self.executes.append((sql, params))
        if "INSERT INTO apply_plans" in sql:
            self._next_id += 1
            self._rows[self._next_id] = {"id": self._next_id, "status": "armed"}
            return self._next_id
        return 0

    async def fetch_one(self, sql: str, params: tuple[Any, ...] = ()) -> dict[str, Any] | None:
        if "SELECT * FROM apply_plans" in sql:
            plan_id = int(params[0]) if params else 0
            row = self._rows.get(plan_id)
            if row is None:
                return None
            return {
                "id": row["id"],
                "target": f"kind-{plan_id}",
                "before_json": "{}",
                "after_json": "{}",
                "rollback_kind": "net_interfaces",
                "bundle_id": None,
                "armed_until": "2099-01-01T00:00:00",
                "status": row["status"],
            }
        return None

    async def fetch_all(self, sql: str, params: tuple[Any, ...] = ()) -> list[dict[str, Any]]:
        return []


def _install_stub_db(monkeypatch: Any) -> _StubDB:
    stub = _StubDB()
    monkeypatch.setattr(apply_state, "get_db", lambda: stub)
    return stub


async def test_rollback_attribution_for_each_kind(monkeypatch: Any) -> None:
    """``rollback(plan_id, username=..., ip=...)`` attributes the audit
    row to the supplied caller regardless of which handler runs. Each
    known kind is exercised to pin Don't #48 across the whole surface
    (#149)."""
    kinds = ("net_interfaces", "ota_slot", "ota_install", "boot_env", "factory_reset", "service_unit", "restore_apply")
    for kind in kinds:
        stub = _install_stub_db(monkeypatch)
        stub.arm_plan(1)

        async def _noop(plan: Any, _kind: str = kind) -> None:
            return None

        monkeypatch.setitem(apply_state._ROLLBACK_HANDLERS, kind, _noop)
        captured: list[dict[str, Any]] = []

        async def _fake_audit_record(captured: list[dict[str, Any]] = captured, **kwargs: Any) -> None:
            captured.append(kwargs)

        monkeypatch.setattr(apply_state.audit, "record", _fake_audit_record)
        await apply_state.rollback(1, reason="manual", username="admin", ip="10.0.0.5")
        assert captured, f"{kind}: rollback() should have called audit.record"
        rec = captured[0]
        assert rec["username"] == "admin", (kind, rec)
        assert rec["ip"] == "10.0.0.5", (kind, rec)


async def test_rollback_defaults_for_watchdog(monkeypatch: Any) -> None:
    """When the watchdog calls ``rollback()`` without kwargs, the
    defaults ``username='system'``/``ip='127.0.0.1'`` are used. This
    test pins that the defaults remain so the watchdog's auto-rollback
    stays visible in the audit log (#149)."""
    _install_stub_db(monkeypatch).arm_plan(1)

    async def _noop(plan: Any) -> None:
        return None

    monkeypatch.setitem(apply_state._ROLLBACK_HANDLERS, "net_interfaces", _noop)
    captured: list[dict[str, Any]] = []

    async def _fake_audit_record(**kwargs: Any) -> None:
        captured.append(kwargs)

    monkeypatch.setattr(apply_state.audit, "record", _fake_audit_record)
    await apply_state.rollback(1, reason="expired")
    assert captured
    rec = captured[0]
    assert rec["username"] == "system", rec
    assert rec["ip"] == "127.0.0.1", rec


async def test_rollback_bundle_attribution(monkeypatch: Any) -> None:
    """``rollback_bundle(bundle_id, username=..., ip=...)`` attributes
    the audit row to the supplied caller (#149). A non-existent bundle
    raises 404 before audit; we just confirm the function never falls
    back to system defaults."""
    _install_stub_db(monkeypatch)
    captured: list[dict[str, Any]] = []

    async def _fake_audit_record(**kwargs: Any) -> None:
        captured.append(kwargs)

    monkeypatch.setattr(apply_state.audit, "record", _fake_audit_record)
    from app.errors import ApiError

    try:
        await apply_state.rollback_bundle("nope", reason="manual", username="op_alice", ip="10.0.0.99")
    except ApiError:
        pass
    for rec in captured:
        assert rec["username"] == "op_alice", rec
        assert rec["ip"] == "10.0.0.99", rec
