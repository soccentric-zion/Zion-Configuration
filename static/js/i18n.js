export const i18n = reactive({
    locale: localStorage.getItem("locale") || "en",
    units: localStorage.getItem("units") || "metric",
});

export function setLocale(l) {
    i18n.locale = l;
    localStorage.setItem("locale", l);
}
export function setUnits(u) {
    i18n.units = u;
    localStorage.setItem("units", u);
}

export function t(key) {
    const cat = messages[i18n.locale] || messages.en;
    return cat[key] || messages.en[key] || key;
}

// Temperature formatter honoring metric/imperial selection.
export function formatTemp(celsius) {
    if (celsius == null) return "—";
    if (i18n.units === "imperial") return (celsius * 9) / 5 + 32 + " °F";
    return celsius + " °C";
}
