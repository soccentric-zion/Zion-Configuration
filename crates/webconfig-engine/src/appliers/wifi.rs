//! Wi-Fi client applier (spec §4.2).
//!
//! Renders `/etc/wpa_supplicant/wpa_supplicant.conf` from the remembered
//! networks in `config.network.wifi` (multiple SSIDs with priority + PSK +
//! hidden flag) and applies the regulatory domain via `iw reg set` on the real
//! root. The networkd applier brings the wlan interface up; this applier owns
//! the supplicant configuration. Hidden SSIDs set `scan_ssid=1`.
//!
//! File-writing is exercised against a tempdir sysroot in tests (spec §6); the
//! `iw`/`wpa_cli` verbs run only on the real root.

use std::sync::Mutex;

use crate::applier::{run_cmd, Applier, ApplyError, ApplyOutcome, FileBackup};
use crate::store::Config;
use crate::sysroot::Sysroot;

#[derive(Debug)]
pub struct WifiApplier {
    backup: Mutex<Option<FileBackup>>,
}

impl WifiApplier {
    pub fn new() -> Self {
        Self {
            backup: Mutex::new(None),
        }
    }

    fn conf_path(sysroot: &Sysroot) -> std::path::PathBuf {
        sysroot.join("/etc/wpa_supplicant/wpa_supplicant.conf")
    }

    /// Render a wpa_supplicant.conf from the remembered networks (spec §4.2).
    pub fn render(networks: &[crate::store::network::WifiNetwork]) -> String {
        let mut s = String::new();
        s.push_str("# Generated by SoCcentric WebConfig — do not edit by hand\n");
        s.push_str("ctrl_interface=/var/run/wpa_supplicant\n");
        s.push_str("ctrl_interface_group=0\n");
        s.push_str("update_config=1\n\n");
        // Highest priority first so the supplicant prefers them (wpa_supplicant
        // picks the highest-priority visible network).
        let mut sorted: Vec<&crate::store::network::WifiNetwork> = networks.iter().collect();
        sorted.sort_by_key(|n| std::cmp::Reverse(n.priority));
        for net in sorted {
            s.push_str("network={\n");
            s.push_str(&format!("    ssid=\"{}\"\n", escape_ssid(&net.ssid)));
            if let Some(psk) = &net.psk {
                if psk.len() == 64 && psk.bytes().all(|b| b.is_ascii_hexdigit()) {
                    // Raw 256-bit hex key (no quoting).
                    s.push_str(&format!("    psk={psk}\n"));
                } else {
                    s.push_str(&format!("    psk=\"{}\"\n", escape_psk(psk)));
                }
            } else {
                // Open network.
                s.push_str("    key_mgmt=NONE\n");
            }
            s.push_str(&format!("    priority={}\n", net.priority));
            if net.hidden {
                s.push_str("    scan_ssid=1\n");
            }
            s.push_str("}\n\n");
        }
        s
    }

    fn validate_network(net: &crate::store::network::WifiNetwork) -> Result<(), ApplyError> {
        if net.ssid.is_empty() {
            return Err(ApplyError::Validation {
                stage: crate::applier::ApplyStage::Validate,
                message: "wifi network with empty SSID".into(),
            });
        }
        // 802.11 SSID limit is 32 bytes.
        if net.ssid.len() > 32 {
            return Err(ApplyError::Validation {
                stage: crate::applier::ApplyStage::Validate,
                message: format!("wifi SSID {:?} exceeds 32 bytes", net.ssid),
            });
        }
        if let Some(psk) = &net.psk {
            let raw_hex = psk.len() == 64 && psk.bytes().all(|b| b.is_ascii_hexdigit());
            if !raw_hex && (psk.len() < 8 || psk.len() > 63) {
                return Err(ApplyError::Validation {
                    stage: crate::applier::ApplyStage::Validate,
                    message: format!(
                        "wifi PSK for {:?} must be 8..=63 chars (or a 64-hex raw key)",
                        net.ssid
                    ),
                });
            }
        }
        Ok(())
    }

    fn validate_reg_domain(domain: &str) -> Result<(), ApplyError> {
        if domain.is_empty() {
            return Err(ApplyError::Validation {
                stage: crate::applier::ApplyStage::Validate,
                message: "regulatory_domain is empty".into(),
            });
        }
        // ISO 3166-1 alpha-2: two ASCII letters.
        if domain.len() != 2 || !domain.bytes().all(|b| b.is_ascii_alphabetic()) {
            return Err(ApplyError::Validation {
                stage: crate::applier::ApplyStage::Validate,
                message: format!("regulatory_domain {domain:?} is not a 2-letter country code"),
            });
        }
        Ok(())
    }
}

impl Default for WifiApplier {
    fn default() -> Self {
        Self::new()
    }
}

impl Applier for WifiApplier {
    fn id(&self) -> &'static str {
        "wifi"
    }

    fn validate(&self, _sysroot: &Sysroot, config: &Config) -> Result<(), ApplyError> {
        for net in &config.network.wifi {
            Self::validate_network(net)?;
        }
        if let Some(domain) = &config.network.regulatory_domain {
            Self::validate_reg_domain(domain)?;
        }
        Ok(())
    }

    fn apply(&self, sysroot: &Sysroot, config: &Config) -> Result<ApplyOutcome, ApplyError> {
        for net in &config.network.wifi {
            Self::validate_network(net)?;
        }
        if let Some(domain) = &config.network.regulatory_domain {
            Self::validate_reg_domain(domain)?;
        }

        let path = Self::conf_path(sysroot);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let backup = FileBackup::capture(path.clone())?;
        std::fs::write(&path, Self::render(&config.network.wifi))?;
        *self.backup.lock().unwrap() = Some(backup);

        if sysroot.is_real_root() {
            if let Some(domain) = &config.network.regulatory_domain {
                let _ = run_cmd("iw", &["reg", "set", domain]);
            }
            // Reconfigure the supplicant so it picks up the new networks
            // without a full restart (less disruptive to an existing link).
            let _ = run_cmd("wpa_cli", &["reconfigure"]);
        }
        Ok(ApplyOutcome::Committed)
    }

    fn rollback(&self, _sysroot: &Sysroot) -> Result<(), ApplyError> {
        if let Some(b) = self.backup.lock().unwrap().take() {
            b.restore()?;
        }
        Ok(())
    }
}

/// Escape a SSID for embedding inside a wpa_supplicant `ssid="..."` string.
/// Double-quote and backslash are the only characters that need escaping in a
/// wpa_supplicant string value.
fn escape_ssid(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Escape a passphrase the same way (passphrases can legitimately contain
/// quotes/backslashes).
fn escape_psk(s: &str) -> String {
    escape_ssid(s)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::store::network::WifiNetwork;

    fn net(ssid: &str, psk: Option<&str>, priority: i32, hidden: bool) -> WifiNetwork {
        WifiNetwork {
            ssid: ssid.into(),
            psk: psk.map(Into::into),
            priority,
            hidden,
        }
    }

    #[test]
    fn renders_multiple_networks_with_priority_and_hidden() {
        let nets = vec![
            net("Home", Some("passphrase-8"), 5, false),
            net("Secret", Some("passphrase-8"), 10, true),
        ];
        let out = WifiApplier::render(&nets);
        // Higher priority network appears first.
        let secret_pos = out.find("ssid=\"Secret\"").unwrap();
        let home_pos = out.find("ssid=\"Home\"").unwrap();
        assert!(secret_pos < home_pos);
        assert!(out.contains("priority=10"));
        assert!(out.contains("scan_ssid=1"));
        assert!(out.contains("psk=\"passphrase-8\""));
    }

    #[test]
    fn renders_open_network_with_key_mgmt_none() {
        let nets = vec![net("OpenNet", None, 1, false)];
        let out = WifiApplier::render(&nets);
        assert!(out.contains("key_mgmt=NONE"));
        assert!(!out.contains("psk="));
    }

    #[test]
    fn renders_raw_hex_key_unquoted() {
        let hex = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";
        let nets = vec![net("Hex", Some(hex), 1, false)];
        let out = WifiApplier::render(&nets);
        assert!(out.contains(&format!("psk={hex}")));
        assert!(!out.contains(&format!("psk=\"{hex}\"")));
    }

    #[test]
    fn rejects_empty_ssid() {
        let a = WifiApplier::new();
        let sys = Sysroot::at("/tmp/never");
        let mut c = Config::default();
        c.network.wifi.push(net("", Some("passphrase-8"), 1, false));
        assert!(a.validate(&sys, &c).is_err());
    }

    #[test]
    fn rejects_short_psk() {
        let a = WifiApplier::new();
        let sys = Sysroot::at("/tmp/never");
        let mut c = Config::default();
        c.network.wifi.push(net("Short", Some("short"), 1, false));
        assert!(a.validate(&sys, &c).is_err());
    }

    #[test]
    fn rejects_bad_reg_domain() {
        let a = WifiApplier::new();
        let sys = Sysroot::at("/tmp/never");
        let mut c = Config::default();
        c.network.regulatory_domain = Some("USA".into());
        assert!(a.validate(&sys, &c).is_err());
        c.network.regulatory_domain = Some("DE".into());
        assert!(a.validate(&sys, &c).is_ok());
    }

    #[test]
    fn writes_and_rolls_back_wpa_conf() {
        let dir = tempfile::tempdir().unwrap();
        let sys = Sysroot::at(dir.path());
        let a = WifiApplier::new();
        let mut c = Config::default();
        c.network
            .wifi
            .push(net("Home", Some("passphrase-8"), 1, false));
        a.apply(&sys, &c).unwrap();
        let f = sys.join("/etc/wpa_supplicant/wpa_supplicant.conf");
        assert!(f.exists());
        assert!(std::fs::read_to_string(&f)
            .unwrap()
            .contains("ssid=\"Home\""));

        a.rollback(&sys).unwrap();
        assert!(!f.exists());
    }
}
