//! AP provisioning-mode applier (spec §4.2).
//!
//! When `config.network.ap_mode.enabled`, writes a hostapd config + a dnsmasq
//! DHCP config + a static-address networkd unit for the AP interface, and
//! enables+starts `hostapd`/`dnsmasq` on the real root so the device serves
//! the Web UI at 192.168.4.1 (spec §4.2). When disabled, removes the configs
//! and stops+disables the units. The trigger (`no-config` | `gpio-button`)
//! is recorded in config; the *runtime* decision to enter AP mode is made
//! elsewhere (first-boot gate / GPIO poll) — this applier only materializes
//! the chosen state to disk and the unit manager.
//!
//! Config generation is exercised against a tempdir sysroot in tests (spec
//! §6); the systemctl verbs run only on the real root.

use std::sync::Mutex;

use crate::applier::{run_cmd, Applier, ApplyError, ApplyOutcome, FileBackup};
use crate::manifest::WifiRadio;
use crate::store::Config;
use crate::sysroot::Sysroot;

const AP_ADDRESS: &str = "192.168.4.1";
const AP_PREFIX: u8 = 24;
const DHCP_START: &str = "192.168.4.10";
const DHCP_END: &str = "192.168.4.50";

#[derive(Debug)]
pub struct ApApplier {
    /// Radio parameters (interface/hw_mode/channel), snapshotted from the
    /// board manifest at construction (spec §4.9 — zero hardcoded I/O; the
    /// manifest doesn't change at runtime, so a one-time snapshot suffices).
    radio: WifiRadio,
    /// Backups for the three files this applier may create (hostapd, dnsmasq,
    /// networkd AP unit), so rollback restores each prior file (or its
    /// absence).
    backups: Mutex<Vec<FileBackup>>,
}

impl ApApplier {
    pub fn new(radio: &WifiRadio) -> Self {
        Self {
            radio: radio.clone(),
            backups: Mutex::new(Vec::new()),
        }
    }

    fn hostapd_path(sysroot: &Sysroot) -> std::path::PathBuf {
        sysroot.join("/etc/hostapd/hostapd.conf")
    }
    fn dnsmasq_path(sysroot: &Sysroot) -> std::path::PathBuf {
        sysroot.join("/etc/dnsmasq.d/webconfig-ap.conf")
    }
    fn networkd_path(sysroot: &Sysroot) -> std::path::PathBuf {
        sysroot.join("/etc/systemd/network/20-ap.network")
    }

    fn render_hostapd(&self, ap: &crate::store::network::ApMode) -> String {
        let mut s = String::new();
        s.push_str("# Generated by SoCcentric WebConfig — do not edit by hand\n");
        s.push_str(&format!("interface={}\n", self.radio.interface));
        s.push_str("driver=nl80211\n");
        s.push_str(&format!("ssid={}\n", ap.ssid));
        s.push_str(&format!("hw_mode={}\n", self.radio.hw_mode));
        s.push_str(&format!("channel={}\n", self.radio.channel));
        s.push_str("wmm_enabled=1\n");
        s.push_str("auth_algs=1\n");
        s.push_str("wpa=2\n");
        s.push_str(&format!("wpa_passphrase={}\n", ap.passphrase));
        s.push_str("wpa_key_mgmt=WPA-PSK\n");
        s.push_str("wpa_pairwise=CCMP\n");
        s.push_str("rsn_pairwise=CCMP\n");
        s
    }

    fn render_dnsmasq(&self) -> String {
        let mut s = String::new();
        s.push_str("# Generated by SoCcentric WebConfig — do not edit by hand\n");
        s.push_str(&format!("interface={}\n", self.radio.interface));
        s.push_str("bind-interfaces\n");
        s.push_str(&format!(
            "dhcp-range={DHCP_START},{DHCP_END},255.255.255.0,12h\n"
        ));
        s
    }

    fn render_networkd(&self) -> String {
        let mut s = String::new();
        s.push_str("# Generated by SoCcentric WebConfig — AP provisioning\n");
        s.push_str("[Match]\n");
        s.push_str(&format!("Name={}\n\n", self.radio.interface));
        s.push_str("[Network]\n");
        s.push_str(&format!("Address={AP_ADDRESS}/{AP_PREFIX}\n"));
        s.push_str("DHCPServer=yes\n");
        s
    }

    fn validate(ap: &crate::store::network::ApMode) -> Result<(), ApplyError> {
        if ap.ssid.is_empty() || ap.ssid.len() > 32 {
            return Err(ApplyError::Validation {
                stage: crate::applier::ApplyStage::Validate,
                message: "AP SSID must be 1..=32 bytes".into(),
            });
        }
        if ap.passphrase.len() < 8 || ap.passphrase.len() > 63 {
            return Err(ApplyError::Validation {
                stage: crate::applier::ApplyStage::Validate,
                message: "AP passphrase must be 8..=63 chars (WPA-PSK)".into(),
            });
        }
        if ap.trigger != "no-config" && ap.trigger != "gpio-button" {
            return Err(ApplyError::Validation {
                stage: crate::applier::ApplyStage::Validate,
                message: format!("AP trigger {:?} must be no-config|gpio-button", ap.trigger),
            });
        }
        Ok(())
    }
}

impl Applier for ApApplier {
    fn id(&self) -> &'static str {
        "ap"
    }

    fn validate(&self, _sysroot: &Sysroot, config: &Config) -> Result<(), ApplyError> {
        Self::validate(&config.network.ap_mode)
    }

    fn apply(&self, sysroot: &Sysroot, config: &Config) -> Result<ApplyOutcome, ApplyError> {
        let ap = &config.network.ap_mode;
        Self::validate(ap)?;

        let mut backups = self.backups.lock().unwrap();
        backups.clear();

        if ap.enabled {
            // hostapd config.
            let hostapd = Self::hostapd_path(sysroot);
            if let Some(parent) = hostapd.parent() {
                std::fs::create_dir_all(parent)?;
            }
            backups.push(FileBackup::capture(hostapd.clone())?);
            std::fs::write(&hostapd, self.render_hostapd(ap))?;

            // dnsmasq DHCP config.
            let dnsmasq = Self::dnsmasq_path(sysroot);
            if let Some(parent) = dnsmasq.parent() {
                std::fs::create_dir_all(parent)?;
            }
            backups.push(FileBackup::capture(dnsmasq.clone())?);
            std::fs::write(&dnsmasq, self.render_dnsmasq())?;

            // Static-address networkd unit for the AP interface.
            let networkd = Self::networkd_path(sysroot);
            if let Some(parent) = networkd.parent() {
                std::fs::create_dir_all(parent)?;
            }
            backups.push(FileBackup::capture(networkd.clone())?);
            std::fs::write(&networkd, self.render_networkd())?;

            if sysroot.is_real_root() {
                crate::applier::run_cmd("networkctl", &["reload"])?;
                let _ = run_cmd("systemctl", &["enable", "--now", "hostapd.service"]);
                let _ = run_cmd("systemctl", &["enable", "--now", "dnsmasq.service"]);
            }
        } else {
            // Disabled: remove our configs (backups remember prior content so
            // rollback can restore), and stop+disable the units on real root.
            for path in [
                Self::hostapd_path(sysroot),
                Self::dnsmasq_path(sysroot),
                Self::networkd_path(sysroot),
            ] {
                backups.push(FileBackup::capture(path.clone())?);
                if path.exists() {
                    std::fs::remove_file(&path)?;
                }
            }
            if sysroot.is_real_root() {
                let _ = run_cmd("systemctl", &["stop", "hostapd.service"]);
                let _ = run_cmd("systemctl", &["disable", "hostapd.service"]);
                let _ = run_cmd("systemctl", &["stop", "dnsmasq.service"]);
                let _ = run_cmd("systemctl", &["disable", "dnsmasq.service"]);
                let _ = crate::applier::run_cmd("networkctl", &["reload"]);
            }
        }
        Ok(ApplyOutcome::Committed)
    }

    fn rollback(&self, sysroot: &Sysroot) -> Result<(), ApplyError> {
        let mut backups = self.backups.lock().unwrap();
        for b in backups.drain(..) {
            b.restore()?;
        }
        if sysroot.is_real_root() {
            let _ = crate::applier::run_cmd("networkctl", &["reload"]);
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::store::network::ApMode;

    fn ap(enabled: bool) -> ApMode {
        ApMode {
            enabled,
            trigger: "no-config".into(),
            ssid: "SoCcentric-Setup".into(),
            passphrase: "change-me-now".into(),
        }
    }

    #[test]
    fn rejects_short_ap_passphrase() {
        let a = ApApplier::new(&WifiRadio::default());
        let sys = Sysroot::at("/tmp/never");
        let mut c = Config::default();
        c.network.ap_mode = ap(true);
        c.network.ap_mode.passphrase = "short".into();
        assert!(a.validate(&sys, &c).is_err());
    }

    #[test]
    fn rejects_bad_trigger() {
        let a = ApApplier::new(&WifiRadio::default());
        let sys = Sysroot::at("/tmp/never");
        let mut c = Config::default();
        c.network.ap_mode = ap(true);
        c.network.ap_mode.trigger = "magic".into();
        assert!(a.validate(&sys, &c).is_err());
    }

    #[test]
    fn enabled_writes_hostapd_dnsmasq_and_networkd() {
        let dir = tempfile::tempdir().unwrap();
        let sys = Sysroot::at(dir.path());
        let a = ApApplier::new(&WifiRadio::default());
        let mut c = Config::default();
        c.network.ap_mode = ap(true);
        a.apply(&sys, &c).unwrap();
        let hostapd = std::fs::read_to_string(sys.join("/etc/hostapd/hostapd.conf")).unwrap();
        assert!(hostapd.contains("interface=wlan0"));
        assert!(hostapd.contains("ssid=SoCcentric-Setup"));
        assert!(hostapd.contains("wpa_passphrase=change-me-now"));
        let dnsmasq =
            std::fs::read_to_string(sys.join("/etc/dnsmasq.d/webconfig-ap.conf")).unwrap();
        assert!(dnsmasq.contains("dhcp-range=192.168.4.10,192.168.4.50"));
        let net = std::fs::read_to_string(sys.join("/etc/systemd/network/20-ap.network")).unwrap();
        assert!(net.contains("Address=192.168.4.1/24"));
        assert!(net.contains("DHCPServer=yes"));
    }

    #[test]
    fn disabled_removes_configs() {
        let dir = tempfile::tempdir().unwrap();
        let sys = Sysroot::at(dir.path());
        let a = ApApplier::new(&WifiRadio::default());
        let mut c = Config::default();
        c.network.ap_mode = ap(true);
        a.apply(&sys, &c).unwrap();
        assert!(sys.join("/etc/hostapd/hostapd.conf").exists());

        c.network.ap_mode = ap(false);
        a.apply(&sys, &c).unwrap();
        assert!(!sys.join("/etc/hostapd/hostapd.conf").exists());
        assert!(!sys.join("/etc/dnsmasq.d/webconfig-ap.conf").exists());
        assert!(!sys.join("/etc/systemd/network/20-ap.network").exists());
    }

    #[test]
    fn rollback_removes_generated_files() {
        let dir = tempfile::tempdir().unwrap();
        let sys = Sysroot::at(dir.path());
        let a = ApApplier::new(&WifiRadio::default());
        let mut c = Config::default();
        c.network.ap_mode = ap(true);
        a.apply(&sys, &c).unwrap();
        let f = sys.join("/etc/hostapd/hostapd.conf");
        assert!(f.exists());
        a.rollback(&sys).unwrap();
        assert!(!f.exists());
    }

    #[test]
    fn manifest_radio_overrides_interface_hw_mode_and_channel() {
        let dir = tempfile::tempdir().unwrap();
        let sys = Sysroot::at(dir.path());
        let radio = WifiRadio {
            interface: "wlan1".into(),
            hw_mode: "a".into(),
            channel: 36,
        };
        let a = ApApplier::new(&radio);
        let mut c = Config::default();
        c.network.ap_mode = ap(true);
        a.apply(&sys, &c).unwrap();

        let hostapd = std::fs::read_to_string(sys.join("/etc/hostapd/hostapd.conf")).unwrap();
        assert!(hostapd.contains("interface=wlan1"));
        assert!(hostapd.contains("hw_mode=a"));
        assert!(hostapd.contains("channel=36"));
        assert!(!hostapd.contains("interface=wlan0"));

        let dnsmasq =
            std::fs::read_to_string(sys.join("/etc/dnsmasq.d/webconfig-ap.conf")).unwrap();
        assert!(dnsmasq.contains("interface=wlan1"));

        let net = std::fs::read_to_string(sys.join("/etc/systemd/network/20-ap.network")).unwrap();
        assert!(net.contains("Name=wlan1"));
    }
}
