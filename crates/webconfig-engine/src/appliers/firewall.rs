//! Firewall applier — service-based nftables (spec §4.2).
//!
//! No rule editor: checkboxes per known service per interface; the backend
//! generates nftables rules. Default: everything closed except the UI (spec
//! §4.2). Writes `/etc/nftables.d/webconfig.nft` and reloads nftables on the
//! real root.

use std::sync::Mutex;

use crate::applier::{run_cmd, Applier, ApplyError, ApplyOutcome, FileBackup};
use crate::store::network::OpenPort;
use crate::store::Config;
use crate::sysroot::Sysroot;

/// Known services the firewall can open (spec §4.2: Web UI 443, SSH 22, MQTT
/// 1883, Modbus 502, …). Extending this list is the only place a new
/// service port is added — the UI reads it via the API.
pub const KNOWN_SERVICES: &[(&str, &str, u16, &str)] = &[
    ("web-ui", "Web UI (HTTPS)", 443, "tcp"),
    ("web-ui-http", "Web UI (HTTP, opt-in)", 80, "tcp"),
    ("ssh", "SSH", 22, "tcp"),
    ("mqtt", "MQTT", 1883, "tcp"),
    ("mqtt-tls", "MQTT over TLS", 8883, "tcp"),
    ("modbus", "Modbus TCP", 502, "tcp"),
    ("https", "HTTPS (app)", 8443, "tcp"),
    ("snmp", "SNMP", 161, "udp"),
];

pub fn service_port(id: &str) -> Option<(u16, &'static str)> {
    KNOWN_SERVICES
        .iter()
        .find(|(s, _, _, _)| *s == id)
        .map(|(_, _, p, proto)| (*p, *proto))
}

#[derive(Debug)]
pub struct FirewallApplier {
    backup: Mutex<Option<FileBackup>>,
}

impl FirewallApplier {
    pub fn new() -> Self {
        Self {
            backup: Mutex::new(None),
        }
    }

    fn nft_file(sysroot: &Sysroot) -> std::path::PathBuf {
        sysroot.join("/etc/nftables.d/webconfig.nft")
    }

    /// Render the nftables ruleset. Default-deny input; the loopback and
    /// established/related flows are allowed; then per-interface open services.
    pub fn render(config: &Config) -> String {
        let mut s = String::new();
        s.push_str("# Generated by SoCcentric WebConfig — do not edit by hand\n");
        s.push_str("table inet webconfig {\n");
        s.push_str("  chain input {\n");
        s.push_str("    type filter hook input priority 0; policy drop;\n");
        s.push_str("    iifname \"lo\" accept\n");
        s.push_str("    ct state established,related accept\n");
        s.push_str("    ct state invalid drop\n");
        // Always allow the UI on any interface so the admin never locks
        // themselves out (spec §4.2: default everything closed except the UI).
        s.push_str("    # UI always reachable\n");
        s.push_str("    tcp dport 443 accept\n");
        s.push_str(&format!(
            "    tcp dport 80 {}\n",
            if config.security.allow_plain_http {
                "accept"
            } else {
                "drop"
            }
        ));
        for iface in &config.network.interfaces {
            if !iface.enabled {
                continue;
            }
            for svc in &iface.open_services {
                if svc == "web-ui" || svc == "web-ui-http" {
                    continue; // already handled above
                }
                if let Some((port, proto)) = service_port(svc) {
                    s.push_str(&format!(
                        "    iifname \"{}\" {} dport {} accept\n",
                        iface.name, proto, port
                    ));
                }
            }
            for open_port in &iface.open_ports {
                s.push_str(&format!(
                    "    iifname \"{}\" {} dport {} accept\n",
                    iface.name, open_port.protocol, open_port.port
                ));
            }
        }
        for svc in &config.network.firewall.default_open {
            if let Some((port, proto)) = service_port(svc) {
                s.push_str(&format!("    {proto} dport {port} accept\n"));
            }
        }
        for open_port in &config.network.firewall.default_open_ports {
            s.push_str(&format!(
                "    {} dport {} accept\n",
                open_port.protocol, open_port.port
            ));
        }
        s.push_str("  }\n");
        s.push_str("}\n");
        s
    }
}

impl Default for FirewallApplier {
    fn default() -> Self {
        Self::new()
    }
}

impl Applier for FirewallApplier {
    fn id(&self) -> &'static str {
        "firewall"
    }

    fn validate(&self, _sysroot: &Sysroot, config: &Config) -> Result<(), ApplyError> {
        for iface in &config.network.interfaces {
            for svc in &iface.open_services {
                if service_port(svc).is_none() {
                    return Err(ApplyError::Validation {
                        stage: crate::applier::ApplyStage::Validate,
                        message: format!("unknown service id {svc:?} on iface {}", iface.name),
                    });
                }
            }
            for open_port in &iface.open_ports {
                validate_open_port(open_port, &format!(" on iface {}", iface.name))?;
            }
        }
        for open_port in &config.network.firewall.default_open_ports {
            validate_open_port(open_port, "")?;
        }
        Ok(())
    }

    fn apply(&self, sysroot: &Sysroot, config: &Config) -> Result<ApplyOutcome, ApplyError> {
        let path = Self::nft_file(sysroot);
        let prior = FileBackup::capture(path.clone())?;
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        if config.network.firewall.enabled {
            std::fs::write(&path, Self::render(config))?;
        } else {
            // Firewall disabled (spec §4.2 enabled flag): remove the managed
            // ruleset file so WebConfig imposes no nftables policy. The live
            // kernel table is dropped by `reload_nft` below. Previously
            // `enabled` was ignored and the default-deny ruleset was always
            // generated and loaded.
            let _ = std::fs::remove_file(&path);
        }
        *self.backup.lock().unwrap() = Some(prior);
        if sysroot.is_real_root() {
            // Re-load the (possibly removed) ruleset. On failure, restore the
            // prior file so we never leave a broken ruleset in place.
            if let Err(e) = Self::reload_nft(&path) {
                let _ = self.backup.lock().unwrap().take().unwrap().restore();
                return Err(e);
            }
        }
        Ok(ApplyOutcome::Committed)
    }

    fn rollback(&self, sysroot: &Sysroot) -> Result<(), ApplyError> {
        if let Some(b) = self.backup.lock().unwrap().take() {
            b.restore()?;
        }
        if sysroot.is_real_root() {
            // Re-load whatever state rollback restored on disk (a prior file, or
            // nothing if we created the file fresh). Previously rollback only
            // restored the file and left the live kernel ruleset stale — the
            // just-applied ruleset stayed in effect until something else
            // reloaded nftables.
            let _ = Self::reload_nft(&Self::nft_file(sysroot));
        }
        Ok(())
    }
}

impl FirewallApplier {
    /// Reload the WebConfig nftables ruleset on the real root. Drops any
    /// existing `inet webconfig` table first so this is idempotent (a plain
    /// `nft -f` fails if the table already exists, which broke re-apply), then
    /// loads the file if it still exists — so apply, disable, and rollback all
    /// converge to the on-disk state. The `delete table` failure is ignored
    /// because the table may not exist yet.
    fn reload_nft(path: &std::path::Path) -> Result<(), ApplyError> {
        let _ = run_cmd("nft", &["delete", "table", "inet", "webconfig"]);
        if path.exists() {
            run_cmd(
                "nft",
                &[
                    "-f",
                    path.to_str().unwrap_or("/etc/nftables.d/webconfig.nft"),
                ],
            )?;
        }
        Ok(())
    }
}

fn validate_open_port(open_port: &OpenPort, context: &str) -> Result<(), ApplyError> {
    if open_port.port == 0 || !matches!(open_port.protocol.as_str(), "tcp" | "udp") {
        return Err(ApplyError::Validation {
            stage: crate::applier::ApplyStage::Validate,
            message: format!(
                "open port must use a valid port and tcp|udp protocol{}",
                context
            ),
        });
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::store::network::Interface;

    #[test]
    fn default_deny_but_ui_always_open() {
        let mut c = Config::default();
        c.network.interfaces.push(Interface {
            name: "eth0".into(),
            enabled: true,
            dhcp: true,
            ..Default::default()
        });
        let r = FirewallApplier::render(&c);
        assert!(r.contains("policy drop"));
        assert!(r.contains("tcp dport 443 accept"));
    }

    #[test]
    fn opens_service_on_interface() {
        let mut c = Config::default();
        c.network.interfaces.push(Interface {
            name: "eth0".into(),
            enabled: true,
            dhcp: true,
            open_services: vec!["ssh".into(), "mqtt".into()],
            ..Default::default()
        });
        let r = FirewallApplier::render(&c);
        assert!(r.contains("iifname \"eth0\" tcp dport 22 accept"));
        assert!(r.contains("iifname \"eth0\" tcp dport 1883 accept"));
    }

    #[test]
    fn opens_custom_port() {
        let mut c = Config::default();
        c.network.firewall.default_open_ports = vec![OpenPort {
            port: 9000,
            protocol: "tcp".into(),
        }];
        let r = FirewallApplier::render(&c);
        assert!(r.contains("tcp dport 9000 accept"));
    }

    #[test]
    fn rejects_invalid_custom_port() {
        let a = FirewallApplier::new();
        let sys = Sysroot::at("/tmp/never");
        let mut c = Config::default();
        c.network.firewall.default_open_ports = vec![OpenPort {
            port: 9000,
            protocol: "icmp".into(),
        }];
        assert!(a.validate(&sys, &c).is_err());
    }

    #[test]
    fn rejects_unknown_service() {
        let a = FirewallApplier::new();
        let sys = Sysroot::at("/tmp/never");
        let mut c = Config::default();
        c.network.interfaces.push(Interface {
            name: "eth0".into(),
            enabled: true,
            open_services: vec!["no-such-svc".into()],
            ..Default::default()
        });
        assert!(a.validate(&sys, &c).is_err());
    }

    #[test]
    fn writes_and_rolls_back_nft_file() {
        let dir = tempfile::tempdir().unwrap();
        let sys = Sysroot::at(dir.path());
        let a = FirewallApplier::new();
        let mut c = Config::default();
        c.network.interfaces.push(Interface {
            name: "eth0".into(),
            enabled: true,
            open_services: vec!["ssh".into()],
            ..Default::default()
        });
        a.apply(&sys, &c).unwrap();
        let f = sys.join("/etc/nftables.d/webconfig.nft");
        assert!(f.exists());
        a.rollback(&sys).unwrap();
        assert!(!f.exists());
    }

    #[test]
    fn disabled_firewall_writes_no_ruleset() {
        // Pre-seed a ruleset so we can prove apply removes it when disabled.
        let dir = tempfile::tempdir().unwrap();
        let sys = Sysroot::at(dir.path());
        let a = FirewallApplier::new();
        let mut c = Config::default();
        c.network.interfaces.push(Interface {
            name: "eth0".into(),
            enabled: true,
            open_services: vec!["ssh".into()],
            ..Default::default()
        });
        a.apply(&sys, &c).unwrap();
        let f = sys.join("/etc/nftables.d/webconfig.nft");
        assert!(f.exists());
        // Now disable the firewall — the managed ruleset file must be removed.
        c.network.firewall.enabled = false;
        a.apply(&sys, &c).unwrap();
        assert!(!f.exists(), "disabled firewall must not leave a ruleset");
    }

    #[test]
    fn firewall_config_defaults_enabled() {
        // First-boot seed (Config::default()) must ship the firewall ON per
        // spec §4.2 ("default everything closed except the UI").
        assert!(crate::store::network::FirewallConfig::default().enabled);
    }
}
