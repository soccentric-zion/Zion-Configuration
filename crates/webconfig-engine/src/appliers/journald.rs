//! journald config applier (spec §4.6).
//!
//! Volatile (default) vs persistent journal storage, max journal size when
//! persistent (eMMC wear), and one remote syslog destination. Writes
//! `/etc/systemd/journald.conf.d/webconfig.conf` and a remote syslog unit when
//! configured. Per-service log levels are applied by the relevant service's
//! own apply_hook, not here (spec §4.3 / §4.6).

use std::sync::Mutex;

use crate::applier::{run_cmd, Applier, ApplyError, ApplyOutcome, FileBackup};
use crate::store::Config;
use crate::sysroot::Sysroot;

#[derive(Debug)]
pub struct JournaldApplier {
    backup: Mutex<Option<FileBackup>>,
    /// Backup of the remote-syslog forwarder unit so rollback restores it.
    unit_backup: Mutex<Option<FileBackup>>,
}

impl JournaldApplier {
    pub fn new() -> Self {
        Self {
            backup: Mutex::new(None),
            unit_backup: Mutex::new(None),
        }
    }

    fn conf_path(sysroot: &Sysroot) -> std::path::PathBuf {
        sysroot.join("/etc/systemd/journald.conf.d/webconfig.conf")
    }

    fn forwarder_path(sysroot: &Sysroot) -> std::path::PathBuf {
        sysroot.join("/etc/systemd/system/webconfig-syslog-forward.service")
    }

    /// Render the remote-syslog forwarder unit (spec §4.6: one destination,
    /// host/port/protocol). Assumption (per spec §7, one line): the image
    /// ships `nc` (netcat); the unit pipes `journalctl -f -o cat` to it. `None`
    /// when remote syslog is disabled or unset — the caller removes the unit.
    pub fn render_forwarder(config: &Config) -> Option<String> {
        let rs = config.logs.remote_syslog.as_ref()?;
        if !rs.enabled || rs.host.is_empty() {
            return None;
        }
        let flag = if rs.protocol == "udp" { "-u" } else { "" };
        let exec = if flag.is_empty() {
            format!("journalctl -f -o cat | nc {} {}", rs.host, rs.port)
        } else {
            format!("journalctl -f -o cat | nc {flag} {} {}", rs.host, rs.port)
        };
        let mut s = String::new();
        s.push_str("# Generated by SoCcentric WebConfig — do not edit by hand\n");
        s.push_str("[Unit]\n");
        s.push_str("Description=SoCcentric WebConfig remote syslog forwarder\n");
        s.push_str("After=systemd-journald.service\n\n");
        s.push_str("[Service]\n");
        s.push_str(&format!("ExecStart=/bin/sh -c '{exec}'\n"));
        s.push_str("Restart=always\n\n");
        s.push_str("[Install]\n");
        s.push_str("WantedBy=multi-user.target\n");
        Some(s)
    }

    /// Render a journald drop-in (spec §4.6).
    pub fn render(config: &Config) -> String {
        let l = &config.logs;
        let storage = if l.storage == "persistent" {
            "persistent"
        } else {
            "volatile"
        };
        let mut s = String::new();
        s.push_str("# Generated by SoCcentric WebConfig\n");
        s.push_str("[Journal]\n");
        s.push_str(&format!("Storage={storage}\n"));
        if l.storage == "persistent" {
            // Max retention in bytes — eMMC wear protection (spec §4.6).
            s.push_str(&format!("SystemMaxUse={}\n", l.max_size_bytes));
            s.push_str(&format!("SystemMaxFileSize={}\n", l.max_size_bytes));
        }
        if l.retention_days > 0 {
            s.push_str(&format!("MaxRetentionSec={}d\n", l.retention_days));
        }
        s
    }

    fn validate(config: &Config) -> Result<(), ApplyError> {
        let l = &config.logs;
        if l.storage != "volatile" && l.storage != "persistent" && !l.storage.is_empty() {
            return Err(ApplyError::Validation {
                stage: crate::applier::ApplyStage::Validate,
                message: format!(
                    "logs.storage must be volatile|persistent, got {:?}",
                    l.storage
                ),
            });
        }
        if let Some(rs) = &l.remote_syslog {
            if rs.protocol != "udp" && rs.protocol != "tcp" {
                return Err(ApplyError::Validation {
                    stage: crate::applier::ApplyStage::Validate,
                    message: format!(
                        "remote syslog protocol must be udp|tcp, got {:?}",
                        rs.protocol
                    ),
                });
            }
            if rs.host.is_empty() {
                return Err(ApplyError::Validation {
                    stage: crate::applier::ApplyStage::Validate,
                    message: "remote syslog host empty".into(),
                });
            }
            // Confine the host to a safe charset so it can never inject shell
            // metacharacters into the forwarder unit's ExecStart line.
            if !rs
                .host
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'.' || b == b'-' || b == b':')
            {
                return Err(ApplyError::Validation {
                    stage: crate::applier::ApplyStage::Validate,
                    message: format!("remote syslog host {:?} has invalid characters", rs.host),
                });
            }
        }
        Ok(())
    }
}

impl Default for JournaldApplier {
    fn default() -> Self {
        Self::new()
    }
}

impl Applier for JournaldApplier {
    fn id(&self) -> &'static str {
        "journald"
    }

    fn validate(&self, _sysroot: &Sysroot, config: &Config) -> Result<(), ApplyError> {
        Self::validate(config)
    }

    fn apply(&self, sysroot: &Sysroot, config: &Config) -> Result<ApplyOutcome, ApplyError> {
        Self::validate(config)?;
        let path = Self::conf_path(sysroot);
        let prior = FileBackup::capture(path.clone())?;
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&path, Self::render(config))?;
        *self.backup.lock().unwrap() = Some(prior);

        // Remote syslog forwarder (spec §4.6). Materialize the unit when
        // enabled+configured; otherwise remove any unit we previously wrote so
        // a disable actually stops forwarding. Backed up for rollback.
        let unit_path = Self::forwarder_path(sysroot);
        let unit_prior = FileBackup::capture(unit_path.clone())?;
        if let Some(parent) = unit_path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let real = sysroot.is_real_root();
        match Self::render_forwarder(config) {
            Some(unit) => {
                std::fs::write(&unit_path, unit)?;
                if real {
                    let _ = run_cmd("systemctl", &["daemon-reload"]);
                    let _ = run_cmd(
                        "systemctl",
                        &["enable", "--now", "webconfig-syslog-forward.service"],
                    );
                }
            }
            None => {
                if unit_path.exists() {
                    std::fs::remove_file(&unit_path)?;
                }
                if real {
                    let _ = run_cmd("systemctl", &["stop", "webconfig-syslog-forward.service"]);
                    let _ = run_cmd(
                        "systemctl",
                        &["disable", "webconfig-syslog-forward.service"],
                    );
                    let _ = run_cmd("systemctl", &["daemon-reload"]);
                }
            }
        }
        *self.unit_backup.lock().unwrap() = Some(unit_prior);

        if real {
            run_cmd("systemctl", &["restart", "systemd-journald.service"])?;
        }
        Ok(ApplyOutcome::Committed)
    }

    fn rollback(&self, _sysroot: &Sysroot) -> Result<(), ApplyError> {
        if let Some(b) = self.backup.lock().unwrap().take() {
            b.restore()?;
        }
        if let Some(b) = self.unit_backup.lock().unwrap().take() {
            b.restore()?;
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::store::logs::{LogsConfig, RemoteSyslog};

    #[test]
    fn renders_volatile_by_default() {
        let r = JournaldApplier::render(&Config::default());
        assert!(r.contains("Storage=volatile"));
        assert!(!r.contains("SystemMaxUse"));
    }

    #[test]
    fn renders_persistent_with_size_cap() {
        let mut c = Config::default();
        c.logs.storage = "persistent".into();
        c.logs.max_size_bytes = 128 * 1024 * 1024;
        c.logs.retention_days = 30;
        let r = JournaldApplier::render(&c);
        assert!(r.contains("Storage=persistent"));
        assert!(r.contains("SystemMaxUse=134217728"));
        assert!(r.contains("SystemMaxFileSize=134217728"));
        assert!(r.contains("MaxRetentionSec=30d"));
    }

    #[test]
    fn rejects_bad_storage() {
        let a = JournaldApplier::new();
        let sys = Sysroot::at("/tmp/never");
        let c = Config {
            logs: LogsConfig {
                storage: "ramdisk".into(),
                max_size_bytes: 0,
                retention_days: 0,
                remote_syslog: None,
            },
            ..Default::default()
        };
        assert!(a.validate(&sys, &c).is_err());
    }

    #[test]
    fn rejects_bad_syslog_protocol() {
        let a = JournaldApplier::new();
        let sys = Sysroot::at("/tmp/never");
        let mut c = Config::default();
        c.logs.remote_syslog = Some(RemoteSyslog {
            host: "logs.example".into(),
            port: 514,
            protocol: "icmp".into(),
            enabled: true,
        });
        assert!(a.validate(&sys, &c).is_err());
    }

    #[test]
    fn renders_tcp_forwarder_unit_when_enabled() {
        let mut c = Config::default();
        c.logs.remote_syslog = Some(RemoteSyslog {
            host: "logs.example.com".into(),
            port: 514,
            protocol: "tcp".into(),
            enabled: true,
        });
        let unit = JournaldApplier::render_forwarder(&c).expect("enabled → unit");
        assert!(
            unit.contains("webconfig-syslog-forward.service")
                || unit.contains("remote syslog forwarder")
        );
        assert!(unit.contains("nc logs.example.com 514"));
        assert!(!unit.contains("nc -u"));
    }

    #[test]
    fn renders_udp_forwarder_with_u_flag() {
        let mut c = Config::default();
        c.logs.remote_syslog = Some(RemoteSyslog {
            host: "10.0.0.5".into(),
            port: 601,
            protocol: "udp".into(),
            enabled: true,
        });
        let unit = JournaldApplier::render_forwarder(&c).unwrap();
        assert!(unit.contains("nc -u 10.0.0.5 601"));
    }

    #[test]
    fn no_forwarder_when_disabled_or_unset() {
        let mut c = Config::default();
        c.logs.remote_syslog = Some(RemoteSyslog {
            host: "logs.example".into(),
            port: 514,
            protocol: "tcp".into(),
            enabled: false,
        });
        assert!(JournaldApplier::render_forwarder(&c).is_none());
        let c2 = Config::default();
        assert!(JournaldApplier::render_forwarder(&c2).is_none());
    }

    #[test]
    fn rejects_host_with_shell_metacharacters() {
        let a = JournaldApplier::new();
        let sys = Sysroot::at("/tmp/never");
        let mut c = Config::default();
        c.logs.remote_syslog = Some(RemoteSyslog {
            host: "logs; rm -rf /".into(),
            port: 514,
            protocol: "tcp".into(),
            enabled: true,
        });
        assert!(a.validate(&sys, &c).is_err());
    }

    #[test]
    fn apply_writes_and_removes_forwarder_unit() {
        let dir = tempfile::tempdir().unwrap();
        let sys = Sysroot::at(dir.path());
        let a = JournaldApplier::new();
        let mut c = Config::default();
        c.logs.remote_syslog = Some(RemoteSyslog {
            host: "logs.example".into(),
            port: 514,
            protocol: "tcp".into(),
            enabled: true,
        });
        a.apply(&sys, &c).unwrap();
        let unit = sys.join("/etc/systemd/system/webconfig-syslog-forward.service");
        assert!(unit.exists(), "enabled → forwarder unit written");
        assert!(std::fs::read_to_string(&unit)
            .unwrap()
            .contains("nc logs.example 514"));

        // Disabling removes the unit.
        c.logs.remote_syslog.as_mut().unwrap().enabled = false;
        a.apply(&sys, &c).unwrap();
        assert!(!unit.exists(), "disabled → forwarder unit removed");

        // Rollback undoes the last (disabling) apply: it captured the unit
        // present before removing it, so rollback restores the unit.
        a.rollback(&sys).unwrap();
        assert!(unit.exists(), "rollback restores the prior forwarder unit");
    }
}
